# Петя и Ваня обмениваются сообщениями на бумажках. И чтобы никто другой не понял что на них написано, все сообщения они записывают в двоичном коде. Но им очень не нравится, что для передачи даже короткого сообщения, приходится писать много единиц и нолей. Поэтому им нужна такая кодировка, в которой итоговая последовательность нулей и единиц минимальна.
#
# Помогите ребятам найти такую кодировку, при помощи алгоритма Хаффмана.
#
# Посчитайте длину сообщения, в двоичной форме, после применения кодирования Хаффмана.
#
# Описание входных данных
#
# В единственной строке входных данных подаётся сообщение от Пети длинной
# n
# , которое нужно закодировать.
#
# Описание выходных данных
#
# В единственной строке выведите длину зашифрованного сообщения от Пети.
#
# Формат ввода
# abbccc
# Формат вывода
# 9
import sys
import heapq
from collections import Counter

def main():
    s = sys.stdin.readline().strip()
    if not s:
        print(0)
        return

    freq = Counter(s)
    heap = list(freq.values())
    heapq.heapify(heap)

    total = 0

    if len(heap) == 1:
        print(heap[0])
        return

    while len(heap) > 1:
        a = heapq.heappop(heap)
        b = heapq.heappop(heap)
        total += a + b
        heapq.heappush(heap, a + b)

    print(total)


if __name__ == "__main__":
    main()